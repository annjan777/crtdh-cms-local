#!/usr/bin/env node
// After `react-router build`: 404.html, sitemap.xml, robots.txt, CSP hashes and .htaccess.
import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { PAGES } from '../src/site/registry.js'

const out = path.resolve(process.env.BUILD_OUTPUT_DIR || process.env.BUILD_DIR || 'build/client') // BUILD_OUTPUT_DIR: publish worker
const site = (process.env.SITE_URL || 'https://crtdh.iitkgp.ac.in').replace(/\/$/, '')
const contactApi = process.env.CONTACT_API_URL || ''
const turnstile = !!process.env.TURNSTILE_SITE_KEY

// 1. Designed 404 at the root, as static hosts expect. The prerendered /404 route stays out of the sitemap.
fs.copyFileSync(path.join(out, '404', 'index.html'), path.join(out, '404.html'))
fs.rmSync(path.join(out, '404'), { recursive: true, force: true })
// The SPA fallback is not used: every route is prerendered and unknown paths get 404.html.
fs.rmSync(path.join(out, '__spa-fallback.html'), { force: true })

// 2. sitemap.xml + robots.txt
const snap = readSnapshot()
const lastmod = (snap?.published_at || new Date().toISOString()).slice(0, 10)
const urls = PAGES.map((p) => `  <url><loc>${site}${p.path}</loc><lastmod>${lastmod}</lastmod></url>`).join('\n')
fs.writeFileSync(
  path.join(out, 'sitemap.xml'),
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}\n</urlset>\n`,
)
fs.writeFileSync(path.join(out, 'robots.txt'), `User-agent: *\nAllow: /\n\nSitemap: ${site}/sitemap.xml\n`)

// 3. sha256 of every inline <script> (React Router hydration bootstrap, JSON-LD) for a strict CSP.
const hashes = new Set()
for (const file of htmlFiles(out)) {
  const html = fs.readFileSync(file, 'utf8')
  for (const m of html.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g)) {
    if (!m[1]) continue
    hashes.add(`'sha256-${crypto.createHash('sha256').update(m[1], 'utf8').digest('base64')}'`)
  }
}
const scriptHashes = [...hashes].sort()

// Embeds actually used by the built pages (frame-src lists only these).
const allHtml = htmlFiles(out).map((f) => fs.readFileSync(f, 'utf8')).join('\n')
const frameOrigins = new Set()
for (const m of allHtml.matchAll(/<iframe[^>]*\ssrc="(https:\/\/[^"/]+)/g)) frameOrigins.add(m[1])
if (allHtml.includes('data-youtube=')) frameOrigins.add('https://www.youtube-nocookie.com') // poster swaps in the player on press
if (allHtml.includes('data-map-embed')) frameOrigins.add('https://www.google.com') // map facade swaps in the embed on press
const imgOrigins = new Set()
for (const m of allHtml.matchAll(/<img[^>]*\ssrc="(https?:\/\/[^"/]+)/g)) imgOrigins.add(m[1])
if (imgOrigins.size) console.warn(`postbuild: third-party images in the build: ${[...imgOrigins].join(', ')}`)

// 4. .htaccess (used only if the CIC server honours it; publish-agent discovery decides).
const origin = (u) => {
  try {
    return new URL(u).origin
  } catch {
    return ''
  }
}
const contactOrigin = origin(contactApi)
const tsOrigin = turnstile ? 'https://challenges.cloudflare.com' : ''
fs.writeFileSync(path.join(out, 'csp-hashes.json'), JSON.stringify({ 'script-src': scriptHashes, 'frame-src': [...frameOrigins].sort().concat(tsOrigin ? [tsOrigin] : []), 'connect-src': [contactOrigin].filter(Boolean) }, null, 2) + '\n')
const csp = [
  "default-src 'self'",
  `script-src 'self' ${scriptHashes.join(' ')} ${tsOrigin}`.trim(),
  // React writes style *attributes* (prerendered, then managed by React), so those stay allowed; inline <style>
  // elements, the CSS-injection vector that can carry selectors, are not (R-15 / F-12). style-src is the fallback
  // for browsers without the -elem/-attr directives.
  "style-src 'self' 'unsafe-inline'",
  "style-src-elem 'self'",
  "style-src-attr 'unsafe-inline'",
  `img-src 'self' data: ${[...imgOrigins].join(' ')}`.trim(),
  "font-src 'self'",
  `connect-src 'self' ${contactOrigin}`.trim(),
  frameOrigins.size || tsOrigin ? `frame-src ${[...frameOrigins].sort().join(' ')} ${tsOrigin}`.replace(/\s+/g, ' ').trim() : "frame-src 'none'",
  "frame-ancestors 'none'",
  "base-uri 'self'",
  `form-action 'self' ${contactOrigin}`.trim(),
  "object-src 'none'",
].join('; ')
// Pages of the old hand-written site (crtdh.iitkgp.ac.in before the CMS) and where they live now.
const LEGACY_PAGES = [
  ['about.html', '/about/'],
  ['team.html', '/team/'],
  ['innovations.html', '/innovations/'],
  ['facilities.html', '/facilities/'],
  ['services.html', '/services/'],
  ['product.html', '/product/'],
  ['enterprises.html', '/enterprises/'],
  ['social-impact.html', '/social-impact/'],
  ['media.html', '/media/'],
  ['contact.html', '/contact/'],
]
const htaccess = `# Generated by frontend/scripts/postbuild.mjs — do not edit by hand.
#
# Needs only "AllowOverride FileInfo" (ErrorDocument, Header, SetEnvIf, AddType). Nothing here needs
# Options, Indexes, AuthConfig or Limit: on a host that allows FileInfo only, any such directive would
# turn every request into a 500. So there is no "Options -Indexes" (every directory of the build has an
# index.html; the publish agent puts one in _media/), no DirectorySlash (needs Indexes; Apache's default
# is On, which is what the trailing-slash URLs expect) and no mod_expires (ExpiresActive needs Indexes;
# Cache-Control is set with mod_headers instead). Each module's block is guarded, so a missing module
# drops its block instead of failing the request.
ErrorDocument 404 /404.html

# The old hand-written site used /about.html, /team.html and so on. Send those (bookmarks, search results,
# links on other sites) to the new pages for good. Redirect is mod_alias and allowed under FileInfo.
# /index.html is left alone: it is the new home page's own file, and redirecting it would loop.
<IfModule mod_alias.c>
${LEGACY_PAGES.map(([from, to]) => `  RedirectMatch 301 ^/${from.replace('.', '\\.')}$ ${to}`).join('\n')}
</IfModule>

<IfModule mod_headers.c>
  Header always set Content-Security-Policy "${csp}"
  Header always set Strict-Transport-Security "max-age=31536000; includeSubDomains"
  Header always set X-Content-Type-Options "nosniff"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
  Header always set Permissions-Policy "camera=(), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=()"
  Header always set X-Frame-Options "DENY"
  Header always set Cross-Origin-Opener-Policy "same-origin"

  # Default: short cache (favicons and other unhashed files).
  Header set Cache-Control "public, max-age=300"
  # Hashed build assets never change: cache for a year. Pages and data revalidate.
  <FilesMatch "\\.(js|css|woff2)$">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </FilesMatch>
  <FilesMatch "\\.(html|data|xml|txt|json)$">
    Header set Cache-Control "no-cache"
  </FilesMatch>
</IfModule>

# Content-hashed media (/_media/<hash>) never change either.
<IfModule mod_setenvif.c>
  SetEnvIf Request_URI "^/(assets|_media)/" LONG_CACHE
  <IfModule mod_headers.c>
    Header set Cache-Control "public, max-age=31536000, immutable" env=LONG_CACHE
  </IfModule>
</IfModule>

<IfModule mod_mime.c>
  AddType application/manifest+json .webmanifest
  AddType image/avif .avif
  AddType image/webp .webp
  AddType font/woff2 .woff2
</IfModule>
`
fs.writeFileSync(path.join(out, '.htaccess'), htaccess)
// No directory listings without "Options -Indexes": give assets/ an index of its own.
fs.writeFileSync(path.join(out, 'assets', 'index.html'), '<!doctype html><meta charset="utf-8"><title>CRTDH</title><meta name="robots" content="noindex">\n')
console.log(`postbuild: 404.html, sitemap.xml (${PAGES.length} urls), robots.txt, ${scriptHashes.length} CSP script hashes, .htaccess`)

function readSnapshot() {
  try {
    return JSON.parse(fs.readFileSync(path.resolve(process.env.SNAPSHOT_PATH || 'snapshot.json'), 'utf8'))
  } catch {
    return null
  }
}

function htmlFiles(dir) {
  const res = []
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name)
    if (e.isDirectory() && e.name !== 'assets') res.push(...htmlFiles(p))
    else if (e.name.endsWith('.html')) res.push(p)
  }
  return res
}
