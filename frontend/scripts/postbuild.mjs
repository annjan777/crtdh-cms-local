#!/usr/bin/env node
// After `react-router build`: 404.html, sitemap.xml, robots.txt, CSP hashes and .htaccess.
import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { PAGES } from '../src/site/registry.js'

const out = path.resolve(process.env.BUILD_DIR || 'build/client')
const site = (process.env.SITE_URL || 'https://crtdh.iitkgp.ac.in').replace(/\/$/, '')
const contactApi = process.env.CONTACT_API_URL || ''
const turnstile = !!process.env.TURNSTILE_SITE_KEY

// 1. Designed 404 at the root, as static hosts expect. The prerendered /404 route stays out of the sitemap.
fs.copyFileSync(path.join(out, '404', 'index.html'), path.join(out, '404.html'))
fs.rmSync(path.join(out, '404'), { recursive: true, force: true })
// The SPA fallback is not used: every route is prerendered and unknown paths get 404.html.
fs.rmSync(path.join(out, '__spa-fallback.html'), { force: true })

// 2. sitemap.xml + robots.txt
const snap = readSnapshot()
const lastmod = (snap?.published_at || new Date().toISOString()).slice(0, 10)
const urls = PAGES.map((p) => `  <url><loc>${site}${p.path}</loc><lastmod>${lastmod}</lastmod></url>`).join('\n')
fs.writeFileSync(
  path.join(out, 'sitemap.xml'),
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}\n</urlset>\n`,
)
fs.writeFileSync(path.join(out, 'robots.txt'), `User-agent: *\nAllow: /\n\nSitemap: ${site}/sitemap.xml\n`)

// 3. sha256 of every inline <script> (React Router hydration bootstrap, JSON-LD) for a strict CSP.
const hashes = new Set()
for (const file of htmlFiles(out)) {
  const html = fs.readFileSync(file, 'utf8')
  for (const m of html.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g)) {
    if (!m[1]) continue
    hashes.add(`'sha256-${crypto.createHash('sha256').update(m[1], 'utf8').digest('base64')}'`)
  }
}
const scriptHashes = [...hashes].sort()
fs.writeFileSync(path.join(out, 'csp-hashes.json'), JSON.stringify({ 'script-src': scriptHashes }, null, 2) + '\n')

// 4. .htaccess (used only if the CIC server honours it; publish-agent discovery decides).
const origin = (u) => {
  try {
    return new URL(u).origin
  } catch {
    return ''
  }
}
const contactOrigin = origin(contactApi)
const tsOrigin = turnstile ? 'https://challenges.cloudflare.com' : ''
const csp = [
  "default-src 'self'",
  `script-src 'self' ${scriptHashes.join(' ')} ${tsOrigin}`.trim(),
  "style-src 'self' 'unsafe-inline'", // React style attributes (LQIP colour, focal point) only; no inline <style>
  "img-src 'self' data: https://i.ytimg.com",
  "font-src 'self'",
  `connect-src 'self' ${contactOrigin}`.trim(),
  `frame-src https://www.google.com https://www.youtube-nocookie.com ${tsOrigin}`.trim(),
  "frame-ancestors 'none'",
  "base-uri 'self'",
  `form-action 'self' ${contactOrigin}`.trim(),
  "object-src 'none'",
].join('; ')
const htaccess = `# Generated by frontend/scripts/postbuild.mjs — do not edit by hand.
Options -Indexes
ErrorDocument 404 /404.html
DirectorySlash On

<IfModule mod_headers.c>
  Header always set Content-Security-Policy "${csp}"
  Header always set Strict-Transport-Security "max-age=31536000; includeSubDomains"
  Header always set X-Content-Type-Options "nosniff"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
  Header always set Permissions-Policy "camera=(), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=()"
  Header always set X-Frame-Options "DENY"
  Header always set Cross-Origin-Opener-Policy "same-origin"
</IfModule>

<IfModule mod_expires.c>
  ExpiresActive On
  ExpiresDefault "access plus 5 minutes"
</IfModule>

# Hashed build assets and content-hashed media never change: cache for a year.
<IfModule mod_headers.c>
  <FilesMatch "\\.(js|css|woff2)$">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </FilesMatch>
  <FilesMatch "\\.(html|data|xml|txt|json)$">
    Header set Cache-Control "no-cache"
  </FilesMatch>
</IfModule>
<IfModule mod_headers.c>
  SetEnvIf Request_URI "^/(assets|media)/" LONG_CACHE
  Header set Cache-Control "public, max-age=31536000, immutable" env=LONG_CACHE
</IfModule>

<IfModule mod_mime.c>
  AddType application/manifest+json .webmanifest
  AddType image/avif .avif
  AddType image/webp .webp
  AddType font/woff2 .woff2
</IfModule>
`
fs.writeFileSync(path.join(out, '.htaccess'), htaccess)
console.log(`postbuild: 404.html, sitemap.xml (${PAGES.length} urls), robots.txt, ${scriptHashes.length} CSP script hashes, .htaccess`)

function readSnapshot() {
  try {
    return JSON.parse(fs.readFileSync(path.resolve(process.env.SNAPSHOT_PATH || 'snapshot.json'), 'utf8'))
  } catch {
    return null
  }
}

function htmlFiles(dir) {
  const res = []
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name)
    if (e.isDirectory() && e.name !== 'assets' && e.name !== 'media') res.push(...htmlFiles(p))
    else if (e.name.endsWith('.html')) res.push(p)
  }
  return res
}
