#!/usr/bin/env bash
# CRTDH preprod rehearsal: the whole stack on this machine with PRODUCTION settings (DEBUG=false).
#
#   scripts/preprod.sh up       start everything (state in .preprod/, gitignored)
#   scripts/preprod.sh smoke    edit -> publish -> check the "live" folder on the fake CIC host
#   scripts/preprod.sh e2e [pytest args]   Playwright E2E (--integration --external) against this stack
#   scripts/preprod.sh status   show what is running
#   scripts/preprod.sh down     stop everything (keeps .preprod/ for inspection; `down --wipe` deletes it)
#
# Pieces (QA lane ports, contract §6):
#   PostgreSQL 16 (unix socket in .preprod/pg, no TCP port; runs as the `postgres` OS user)
#     -> falls back to SQLite only if Postgres can't start, with ALLOW_SQLITE=1 and a loud label
#     -> PREPROD_DATABASE_URL=postgres://... uses an existing server instead (CI service container)
#   gunicorn  CMS API (config.wsgi)                  127.0.0.1:8600
#   uvicorn   MCP ASGI (mcp_server.asgi:app)         127.0.0.1:8601   (8601: not assigned to any lane; flagged to lead)
#   publish worker (manage.py run_publish_worker)
#   fake CIC host: SFTP-only server (publish_agent.tests.fakes) 127.0.0.1:2223
#   publish agent (python -m publish_agent run) pointed at that SFTP host and the CMS
#   static hosts: admin (CMS origin, proxies /api) :3600; public site = the SFTP web root :3601
#
# Everything is served over HTTPS with a throwaway self-signed cert (.preprod/tls; production settings refuse
# http origins). Clients trust it via SSL_CERT_FILE/REQUESTS_CA_BUNDLE; browsers use ignore_https_errors.
# Deviations from production (only these): self-signed cert, test users seeded with --rehearsal,
# fake SFTP host instead of academicweb, no Cloudflare Access/Tunnel in front, all on one machine.
set -euo pipefail
REPO=$(cd "$(dirname "$0")/.." && pwd)
ST=${PREPROD_STATE:-$REPO/.preprod}
PY=${PY:-/home/claude/venv/bin/python}
PGBIN=${PGBIN:-$(ls -d /usr/lib/postgresql/*/bin 2>/dev/null | sort -V | tail -1)}
CMS_PORT=8600 MCP_PORT=8601 ADMIN_PORT=3600 SITE_PORT=3601 SFTP_PORT=2223
log() { printf '\033[1m[preprod]\033[0m %s\n' "$*"; }
die() { log "ERROR: $*"; exit 1; }

need_integrated_tree() {
  local missing=()
  [ -d "$REPO/backend/apps/publishing" ] || missing+=("backend/apps/publishing (backend-core)")
  [ -f "$REPO/backend/apps/accounts/mfa.py" ] || missing+=("backend/apps/accounts/mfa.py (backend-security)")
  [ -d "$REPO/backend/mcp_server" ] || missing+=("backend/mcp_server (mcp)")
  [ -d "$REPO/publish_agent" ] || missing+=("publish_agent/ (publish-agent)")
  [ ${#missing[@]} -eq 0 ] || die "this tree is not integrated yet; missing: ${missing[*]}"
}

start_bg() { # name, logfile, cmd...
  local name=$1 logf=$2; shift 2
  setsid nohup "$@" >"$logf" 2>&1 < /dev/null &
  echo $! > "$ST/pids/$name.pid"
  log "started $name (pid $!) -> ${logf#$REPO/}"
}

wait_url() { # url [timeout]
  local end=$((SECONDS + ${2:-60}))
  until curl -s --cacert "$ST/tls/cert.pem" -o /dev/null "$1"; do [ $SECONDS -lt $end ] || die "$1 not up"; sleep 1; done
}

start_db() {
  if [ -n "${PREPROD_DATABASE_URL:-}" ]; then  # e.g. a CI postgres:16 service container
    echo "postgres (external: PREPROD_DATABASE_URL)" > "$ST/DB_MODE"
    echo "DATABASE_URL=$PREPROD_DATABASE_URL" >> "$ST/env"
    return
  fi
  # Postgres refuses to run as root: as root use the postgres OS user, otherwise run as ourselves.
  local AS=(); [ "$(id -u)" = 0 ] && AS=(runuser -u postgres --)
  if [ "${PREPROD_DB:-postgres}" = postgres ] && [ -x "$PGBIN/initdb" ] && { [ ${#AS[@]} -eq 0 ] || id postgres >/dev/null 2>&1; }; then
    mkdir -p "$ST/pg"; [ ${#AS[@]} -eq 0 ] || chown postgres "$ST/pg"
    if [ ! -d "$ST/pg/data" ]; then
      "${AS[@]}" "$PGBIN/initdb" -D "$ST/pg/data" -U crtdh --auth=trust -E UTF8 >/dev/null
    fi
    if "${AS[@]}" "$PGBIN/pg_ctl" -D "$ST/pg/data" -o "-c listen_addresses='' -k $ST/pg" -l "$ST/pg/postgres.log" -w start >/dev/null; then
      psql -h "$ST/pg" -U crtdh -d postgres -tc "select 1 from pg_database where datname='crtdh'" | grep -q 1 \
        || psql -h "$ST/pg" -U crtdh -d postgres -qc "create database crtdh"
      echo "postgres $("$PGBIN/postgres" --version | awk '{print $3}') (unix socket $ST/pg)" > "$ST/DB_MODE"
      echo "DATABASE_URL=postgres://crtdh@/crtdh?host=$ST/pg" >> "$ST/env"
      return
    fi
    log "Postgres failed to start (see pg/postgres.log); falling back to SQLite"
  fi
  echo "SQLITE (ALLOW_SQLITE=1) — NOT production-equivalent: no row locks, different transaction semantics" > "$ST/DB_MODE"
  printf 'DATABASE_URL=sqlite:///%s\nALLOW_SQLITE=1\n' "$ST/db.sqlite3" >> "$ST/env"
}

write_env() {
  umask 077
  cat > "$ST/env" <<ENV
# generated by scripts/preprod.sh — local rehearsal values only, regenerated on every 'up'
CRTDH_ENV=production
DEBUG=False
SECRET_KEY=$(openssl rand -base64 60 | tr -d '\n=+/')
ALLOWED_HOSTS=localhost,127.0.0.1
CORS_ALLOW_ALL_ORIGINS=False
CORS_ALLOWED_ORIGINS=https://localhost:$ADMIN_PORT,https://localhost:$SITE_PORT${PREPROD_EXTRA_ORIGINS:+,$PREPROD_EXTRA_ORIGINS}
CSRF_TRUSTED_ORIGINS=https://localhost:$ADMIN_PORT
SSL_CERT_FILE=$ST/tls/cert.pem
REQUESTS_CA_BUNDLE=$ST/tls/cert.pem
CRTDH_SKIP_DOTENV=1
# Trusted-proxy rule as in deploy/docker-compose.yml: only the gateway (here: the static host on 127.0.0.1)
# may reach the app processes; any other peer (e.g. 127.0.0.5) gets 403. Lets the attack pass test a bypass.
TRUSTED_PROXY_IPS=127.0.0.1
REQUIRE_TRUSTED_PROXY=True
MEDIA_ROOT=$ST/media
PUBLISH_ROOT=$ST/publish
CMS_PUBLIC_URL=https://localhost:$ADMIN_PORT
PUBLIC_SITE_URL=https://localhost:$SITE_PORT
# read by the worker's frontend build (deploy/.env.example sets the same two)
SITE_URL=https://localhost:$SITE_PORT
CONTACT_API_URL=https://localhost:$CMS_PORT/api/v1/contact/
# the worker builds exactly as the production worker image does (deploy/worker/build-site.sh, output outside frontend/)
FRONTEND_BUILD_CMD="sh $REPO/deploy/worker/build-site.sh"
FRONTEND_DIR=$REPO/frontend
FRONTEND_BUILD_OUTPUT=$ST/site/build/client
MCP_PUBLIC_URL=https://localhost:$MCP_PORT
EMAIL_URL=smtp://127.0.0.1:2525
AGENT_HMAC_SECRET=$(openssl rand -hex 32)
TURNSTILE_SECRET=1x0000000000000000000000000000000AA
CRTDH_ALLOW_TEST_SEED=1
CRTDH_TEST_PASSWORD=$(openssl rand -base64 18 | tr -d '\n=+/')
ENV
  umask 022
}

up() {
  need_integrated_tree
  [ -f "$ST/pids/gunicorn.pid" ] && kill -0 "$(cat "$ST/pids/gunicorn.pid")" 2>/dev/null && die "already running (scripts/preprod.sh down)"
  mkdir -p "$ST"/{logs,pids,media,publish,mail,sftp,agent,tls}
  $PY "$REPO/tests/tools/devcert.py" "$ST/tls" >/dev/null
  TLS="--cert $ST/tls/cert.pem --key $ST/tls/key.pem"
  write_env
  start_db
  set -a; . "$ST/env"; set +a
  cd "$REPO/backend"
  log "DB: $(cat "$ST/DB_MODE")"
  log "django check --deploy"
  $PY manage.py check --deploy --fail-level WARNING > "$ST/logs/check-deploy.txt" 2>&1 || log "check --deploy reported issues (logs/check-deploy.txt)"
  $PY manage.py migrate --noinput -v0
  $PY manage.py createcachetable  # prod uses the DB cache (throttles, lockout); missing in the first rehearsal
  $PY manage.py collectstatic --noinput -v0 >/dev/null 2>&1 || true
  cp -r "$REPO/backend/seed_media/." "$MEDIA_ROOT/" 2>/dev/null || true
  if [ ! -f "$ST/seeded" ]; then  # `up` after `down` keeps the database: seed once
    $PY manage.py shell -c "from tests.support.content import *; load_snapshot_into_db(FULL_SNAPSHOT_PATH)"
    touch "$ST/seeded"
  fi
  if ! grep -q '^E2E_OAUTH_CLIENT_ID=' "$ST/env.oauth" 2>/dev/null; then  # Claude connector client (shown once)
    $PY manage.py create_claude_client 2>/dev/null | awk '/Client ID:/{print "E2E_OAUTH_CLIENT_ID="$3} /Client secret:/{print "E2E_OAUTH_CLIENT_SECRET="$3}' > "$ST/env.oauth" || true
    chmod 600 "$ST/env.oauth"
  fi
  $PY manage.py seed_test_users --rehearsal | tail -1 > "$ST/users.json"; chmod 600 "$ST/users.json"
  $PY manage.py create_baseline_snapshot >/dev/null 2>&1 || log "no baseline snapshot command result (ok on first run)"

  [ -d "$REPO/frontend/node_modules" ] || (cd "$REPO/frontend" && npm ci --no-audit --no-fund >/dev/null)
  if [ ! -f "$REPO/admin/dist/index.html" ]; then
    log "building admin"
    (cd "$REPO/admin" && { [ -d node_modules ] || npm ci --no-audit --no-fund >/dev/null; } && VITE_API_BASE_URL=/api/v1 npm run build > "$ST/logs/admin-build.log" 2>&1) \
      || log "WARNING: admin build failed (logs/admin-build.log); CMS UI not served, API-level smoke still runs"
  fi

  start_bg smtp "$ST/logs/smtp.log" $PY "$REPO/tests/tools/smtp_sink.py" --dir "$ST/mail" --port 2525
  start_bg gunicorn "$ST/logs/gunicorn.log" $PY -m gunicorn config.wsgi:application -b 127.0.0.1:$CMS_PORT -w 3 --timeout 120 --certfile "$ST/tls/cert.pem" --keyfile "$ST/tls/key.pem" --access-logfile -
  start_bg mcp "$ST/logs/mcp.log" $PY -m uvicorn mcp_server.asgi:app --host 127.0.0.1 --port $MCP_PORT --no-proxy-headers --ssl-certfile "$ST/tls/cert.pem" --ssl-keyfile "$ST/tls/key.pem"
  start_bg worker "$ST/logs/worker.log" $PY manage.py run_publish_worker
  cd "$REPO"
  start_bg sftp "$ST/logs/sftp.log" $PY tests/tools/sftp_host.py --root "$ST/sftp" --port $SFTP_PORT \
      --client-key "$ST/agent/agent_key" --known-hosts "$ST/agent/known_hosts"
  wait_url "https://localhost:$CMS_PORT/api/v1/auth/csrf/" 60
  for _ in $(seq 20); do [ -s "$ST/agent/known_hosts" ] && break; sleep 0.5; done
  WEBROOT="$ST/sftp/home/u/public_html"
  cat > "$ST/agent/config.ini" <<INI
[cms]
url = https://localhost:$CMS_PORT
secret_env = CRTDH_AGENT_SECRET
poll_seconds = 3
[sftp]
host = 127.0.0.1
port = $SFTP_PORT
user = u
key_file = $ST/agent/agent_key
known_hosts = $ST/agent/known_hosts
[site]
web_root = ~/public_html
strategy = auto
keep_releases = 2
verify_url = https://localhost:$SITE_PORT/
verify_marker = crtdh-build
[agent]
state_dir = $ST/agent/state
INI
  export CRTDH_AGENT_SECRET=$AGENT_HMAC_SECRET
  $PY -m publish_agent -c "$ST/agent/config.ini" check --no-http > "$ST/logs/agent-check.log" 2>&1 || log "agent check reported issues (logs/agent-check.log)"
  start_bg agent "$ST/logs/agent.log" $PY -m publish_agent -c "$ST/agent/config.ini" run
  [ -f "$REPO/admin/dist/index.html" ] && start_bg admin "$ST/logs/admin-static.log" $PY tests/tools/static_server.py --dir "$REPO/admin/dist" --port $ADMIN_PORT --mode spa --proxy https://localhost:$CMS_PORT --static-root "$REPO/backend/staticfiles" $TLS
  # The public site is whatever the agent made live in the SFTP web root (follows its symlink/htaccess switch).
  start_bg site "$ST/logs/site-static.log" $PY tests/tools/static_server.py --dir "$WEBROOT" --port $SITE_PORT --mode static $TLS
  wait_url "https://localhost:$MCP_PORT/" 30 || true
  log "up. DB: $(cat "$ST/DB_MODE")"
  log "CMS https://localhost:$ADMIN_PORT  public https://localhost:$SITE_PORT  MCP https://localhost:$MCP_PORT/mcp (self-signed: .preprod/tls/cert.pem)"
  log "test users in .preprod/users.json; password in .preprod/env (CRTDH_TEST_PASSWORD) — local values only"
}

smoke() { cd "$REPO" && $PY tests/tools/preprod_smoke.py --state "$ST"; }

e2e() { # Playwright E2E (all levels incl. needs_integration) against this running stack
  cd "$REPO"; set -a; . "$ST/env"; [ -f "$ST/env.oauth" ] && . "$ST/env.oauth"; set +a
  E2E_CA_FILE="$ST/tls/cert.pem" E2E_USERS_FILE="$ST/users.json" E2E_PUBLISH_STACK=1 E2E_SEED=full E2E_MAIL_DIR="$ST/mail" \
  E2E_SITE_URL="${E2E_SITE_URL:-https://localhost:$SITE_PORT}" E2E_ADMIN_URL="https://localhost:$ADMIN_PORT" \
  E2E_MCP_URL="https://localhost:$MCP_PORT/mcp" \
    $PY -m pytest $(printf '%s\n' "$@" | grep -q '^tests/' || echo tests/e2e) --integration --external --output test-results/e2e "$@"
}

status() {
  [ -f "$ST/DB_MODE" ] && log "DB: $(cat "$ST/DB_MODE")"
  for f in "$ST"/pids/*.pid; do [ -f "$f" ] || continue; n=$(basename "$f" .pid)
    if kill -0 "$(cat "$f")" 2>/dev/null; then log "$n running ($(cat "$f"))"; else log "$n STOPPED (see logs/$n.log)"; fi; done
}

down() {
  for f in "$ST"/pids/*.pid; do [ -f "$f" ] || continue; kill -TERM -- "-$(cat "$f")" 2>/dev/null || kill "$(cat "$f")" 2>/dev/null || true; rm -f "$f"; done
  local AS=(); [ "$(id -u)" = 0 ] && AS=(runuser -u postgres --)
  [ -d "$ST/pg/data" ] && "${AS[@]}" "$PGBIN/pg_ctl" -D "$ST/pg/data" stop -m fast >/dev/null 2>&1 || true
  log "stopped"
  [ "${1:-}" = "--wipe" ] && rm -rf "$ST" && log "wiped $ST"
  return 0
}

case "${1:-}" in
  up) up ;; smoke) smoke ;; e2e) shift; e2e "$@" ;; status) status ;; down) shift; down "${1:-}" ;;
  *) sed -n '2,9p' "$0"; exit 2 ;;
esac
